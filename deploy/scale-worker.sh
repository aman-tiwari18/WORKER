#!/usr/bin/env bash
#
# scale-worker.sh — bring worker containers up on ANY GPU host by pulling the
# image from ghcr (plan §4.0/§4.7 — continuous scaling).
#
# On a new machine the whole join flow is:
#   1. get on the network that can reach the backend + ghcr.io
#   2. put a worker .env here (copy .env.example, set MAIN_BACKEND_URL/API_KEY/…)
#   3. ./deploy/scale-worker.sh
# It detects the GPUs, pulls ghcr.io/<owner>/cctv-worker, generates one container
# per GPU (each with its own WORKER_INDEX + CUDA device), and starts them. Every
# container registers itself with the fleet registry on boot — no reindexing, no
# hand-edited compose.
#
# Env / flags:
#   IMAGE          registry image (default: ghcr.io/aman-tiwari18/cctv-worker)
#   IMAGE_TAG      tag to run       (default: uat)
#   GPUS           GPU count        (default: auto-detect via nvidia-smi)
#   INDEX_BASE     WORKER_INDEX of the first GPU (default: 0) — set per host so
#                  indexes are globally unique across the fleet in hash mode
#                  (lease mode makes this irrelevant; see COORDINATION_MODE)
#   GHCR_USER / GHCR_TOKEN   creds for a PRIVATE package pull (optional if public)
#   NO_PULL=1      skip docker pull (use a locally-built image)
#
set -euo pipefail
cd "$(dirname "$0")/.."          # project dir (worker repo root)
PROJECT_DIR="$(pwd)"

IMAGE="${IMAGE:-ghcr.io/aman-tiwari18/cctv-worker}"
IMAGE="$(echo "$IMAGE" | tr '[:upper:]' '[:lower:]')"   # ghcr paths are lowercase
IMAGE_TAG="${IMAGE_TAG:-uat}"
INDEX_BASE="${INDEX_BASE:-0}"
COMPOSE_FILE="deploy/docker-compose.generated.yml"

[[ -f .env ]] || { echo "ERROR: no .env in $PROJECT_DIR (copy .env.example and fill it in)"; exit 1; }

# ── detect GPUs ──────────────────────────────────────────────────────────────
if [[ -z "${GPUS:-}" ]]; then
  if command -v nvidia-smi >/dev/null 2>&1; then
    GPUS="$(nvidia-smi -L | wc -l)"
  else
    echo "ERROR: nvidia-smi not found and GPUS not set"; exit 1
  fi
fi
[[ "$GPUS" -ge 1 ]] || { echo "ERROR: GPUS must be >= 1 (got '$GPUS')"; exit 1; }
echo "→ host $(hostname): $GPUS GPU(s), image $IMAGE:$IMAGE_TAG, WORKER_INDEX base $INDEX_BASE"

# ── login + pull from ghcr (skip with NO_PULL=1) ─────────────────────────────
if [[ "${NO_PULL:-0}" != "1" ]]; then
  if [[ -n "${GHCR_TOKEN:-}" ]]; then
    echo "${GHCR_TOKEN}" | docker login ghcr.io -u "${GHCR_USER:-$USER}" --password-stdin
  fi
  echo "→ pulling $IMAGE:$IMAGE_TAG"
  docker pull "$IMAGE:$IMAGE_TAG"
fi

# ── generate one service per GPU ─────────────────────────────────────────────
# Each service: unique container name, WORKER_INDEX, WORKER_ID and pinned GPU.
# Everything else (backend URL, API key, DB mode…) comes from the shared .env.
HOSTNAME_SAFE="$(hostname | tr -c 'A-Za-z0-9_.-' '_')"
{
  echo "# GENERATED by scale-worker.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — do not edit by hand."
  echo "services:"
  for ((g=0; g<GPUS; g++)); do
    idx=$((INDEX_BASE + g))
    cat <<YAML
  worker-gpu${g}:
    image: ${IMAGE}:${IMAGE_TAG}
    container_name: cctv_uat_worker_${HOSTNAME_SAFE}_gpu${g}
    restart: unless-stopped
    shm_size: '16gb'
    env_file: .env
    environment:
      WORKER_MODE: agent
      WORKER_INDEX: "${idx}"
      WORKER_ID: "worker-${HOSTNAME_SAFE}-gpu${g}"
      CUDA_VISIBLE_DEVICES: "${g}"
      WORKER_HOSTNAME: "$(hostname)"
    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - ./models:/app/models
      - ./data:/app/data
      - \${HF_CACHE_HOST_PATH:-./hf_cache}:/app/data/hf_cache
      - ./scripts/logs:/app/scripts/logs
      - \${FRAMES_HOST_PATH:-./results}:/app/scripts/detection/results
    networks: [cctvv2_net]
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              device_ids: ['${g}']
              capabilities: [gpu]
YAML
  done
  echo "networks:"
  echo "  cctvv2_net:"
  echo "    external: true"
} > "$COMPOSE_FILE"

echo "→ generated $COMPOSE_FILE ($GPUS service(s))"

if [[ "${DRY_RUN:-0}" == "1" ]]; then
  echo "→ DRY_RUN: validating compose, not starting containers"
  IMAGE="$IMAGE" IMAGE_TAG="$IMAGE_TAG" \
    docker compose --project-directory "$PROJECT_DIR" -f "$COMPOSE_FILE" config >/dev/null \
    && echo "✓ generated compose is valid"
  exit 0
fi

# ── bring up (Compose v2; v1 crashes on recreate) ────────────────────────────
IMAGE="$IMAGE" IMAGE_TAG="$IMAGE_TAG" \
  docker compose --project-directory "$PROJECT_DIR" -f "$COMPOSE_FILE" up -d
docker compose --project-directory "$PROJECT_DIR" -f "$COMPOSE_FILE" ps
echo "✓ workers up. They self-register with the fleet — check: GET /fleet/summary"
