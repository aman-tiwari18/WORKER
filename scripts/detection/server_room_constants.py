def get_min_persons(tc_code):
    """Return the Maximum Server Room Threshold for a given TC code.
    Falls back to DEFAULT_MIN_PERSONS if tc_code is not in the table."""
    if tc_code:
        key = str(tc_code).strip()
        if key in TC_CODE_THRESHOLDS:
            return TC_CODE_THRESHOLDS[key]
    return DEFAULT_MIN_PERSONS
